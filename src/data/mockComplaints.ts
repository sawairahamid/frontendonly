function records(
  sheetRow: number,
  issue: number,
  notionId: string,
  clickupId: string,
  discordId: string,
): ConnectedRecord[] {
  return [
    {
      connector: "google-sheets",
      label: "Google Sheets",
      reference: `Inbound!A${sheetRow}`,
      url: `https://docs.google.com/spreadsheets/d/demo-hanaz-complaints/edit#gid=0&range=A${sheetRow}`,
      action: "Open Record",
    },
    {
      connector: "github",
      label: "GitHub",
      reference: `hanaz/operations#${issue}`,
      url: `https://github.com/hanaz/operations/issues/${issue}`,
      action: "Open Issue",
    },
    {
      connector: "notion",
      label: "Notion",
      reference: `Support Cases · ${notionId}`,
      url: `https://notion.so/demo/${notionId}`,
      action: "Open Page",
    },
    {
      connector: "clickup",
      label: "ClickUp",
      reference: `Task ${clickupId}`,
      url: `https://app.clickup.com/t/${clickupId}`,
      action: "Open Task",
    },
    {
      connector: "discord",
      label: "Discord",
      reference: `#support-escalations`,
      url: `https://discord.com/channels/demo/support-escalations/${discordId}`,
      action: "View Message",
    },
  ];
}

