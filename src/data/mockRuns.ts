function complaintSteps(
  statuses: StepStatus[],
  durations: string[],
  errors: Record<number, string> = {},
): RunStep[] {
  return complaintPipeline.map((step, i) => ({
    index: i + 1,
    name: step.name,
    connector: step.connector,
    status: statuses[i] ?? "success",
    duration: durations[i] ?? "—",
    error: errors[i + 1],
  }));
}

